export interface ExpectedOutcome {
  metric: string;
  target: string;
}

export interface SlideImage {
  path: string; // e.g. /uploads/slide-images/slide-3-172938.png
  note?: string; // optional operator-written note about how to use the image
}

export interface OutlineSlide {
  slide: number;
  title: string;
  body: string;
  role: string;
  rationale?: string; // Why this slide exists in the narrative, informed by competitor intel
  image?: SlideImage | null;
  include_in_forge?: boolean; // tick-mark: if false, FORGE skips this slide and keeps the existing creative untouched. Defaults to true when undefined.
  use_higgsfield?: boolean; // operator toggled "forge whole slide with Higgsfield" for this slide
  higgsfield_prompt?: string; // optional operator visual-steer for the Higgsfield gen
  higgsfield_rendered?: boolean; // set true by engine after Higgsfield produced the finished slide
  higgsfield_path?: string; // public path of the Higgsfield-rendered finished slide
  user_edited?: boolean;
}

export interface AdConcept {
  variant: number;
  concept: string; // short tag — "proof-forward", "hook-forward", "urgency-visual", or custom
  rationale: string; // WHY this angle for THIS brand, grounded in competitor intel
  headline_direction: string; // what the main hook/offer should communicate
  visual_direction: string; // what the composition should feel like
  image?: SlideImage | null;
  include_in_forge?: boolean; // tick-mark: if false, FORGE skips this variant. Defaults to true when undefined.
  use_higgsfield?: boolean;
  higgsfield_prompt?: string;
  higgsfield_rendered?: boolean;
  higgsfield_path?: string;
  user_edited?: boolean;
}

