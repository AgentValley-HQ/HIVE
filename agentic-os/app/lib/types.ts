// ─── Jev virality scoring ────────────────────────────────────────────────
// Written by engine/virality-score.js after every forge. Carousel scored as
// one creative; each single ad scored on its own. Market layer compares
// against Intel Radar; craft layer judges on its own merits.

export interface ProvenAd {
  competitor: string;
  platform: string;
  days_running: number | null; // winner proxy; null when scraper didn't capture start date
  variant_count: number;       // live versions of the same idea
  hook: string;
  angle: string;               // one line, written by Claude in market-summary.describe()
  visual: string;              // one line, written by Claude in market-summary.describe()
  cta: string;
}

export interface MarketSummary {
  data_quality: {
    source: "real" | "synthetic";
    total_ads_scraped: number;
    has_start_dates: boolean;
    platforms: string[];
    country: string;
    built_at: string;
  };
  brand: {
    business_name: string;
    value_prop: string;
    differentiators: string[];
    tone: string;
    do_not_say: string;
  };
  winning_patterns: string[];
  competitive_gaps: string[];
  visual_language: { common_styles: string[]; overused: string[] };
  proven_ads: ProvenAd[];
}

export interface ViralityScore {
  hive: number | null;    // 0–100 blended score
  market: number | null;  // 0–100, null when intel is synthetic
  craft: number | null;   // 0–100
  parts: {
    proven_pattern?: number | null;
    stands_out?: number | null;
    fills_gap?: number | null;
    scroll_stop?: number | null;
    share_worthy?: number | null;
    clarity?: number | null;
    slop_inverse?: number | null;
    on_brand?: number | null;
    slop?: number | null;
  };
  hook_type: { choice: string; confidence: number } | null;
  closest_angle: { choice: string; confidence: number } | null;
  flags: string[];        // off_brand | reads_like_slop | blends_in
  model: string;
  scored_at: string;
}

export interface ViralityState {
  market_usable: boolean;
  market_source: string;
  weights: Record<string, Record<string, number>>;
  carousel: ViralityScore | null;
  single_ads: Record<string, ViralityScore>;
  single_ad_ranking: { index: number; rank: number }[];
}
