// ─── Ad playbook — per-platform creative recommendations ─────────────────
// Generated by engine/ad-playbook.js once competitor data has been scraped.
// The War Room's AD BUDGET STRATEGY panel renders these as tabbed cards so
// the operator sees exactly WHAT to try on each channel and WHY it should work.

export interface CreativeAngle {
  concept: string; // Short tag — e.g. "Proof-first stat hero"
  angle: string; // 1 sentence — what the creative actually depicts/says
  why_it_works: string; // 2-3 sentences grounded in competitor patterns + brand position
  audience: string; // Specific segment this hits — not generic
  format: string; // e.g. "Single image · 1:1", "Carousel · 5 images"
  cta: string; // The action the creative drives toward
  // When format is a carousel, Claude breaks the creative down into explicit
  // slide specs so the Foundry's carousel pipeline can ship them straight to
  // the carousel_outline (no extra re-prompting needed).
  slides?: CarouselSlideSpec[];
}

export interface CarouselSlideSpec {
  slide: number;
  title: string;
  body: string;
  role: string; // e.g. "hook" | "problem" | "solution" | "proof" | "cta" | "custom"
}

export interface PlatformPlan {
  rationale: string; // Why we're spending this % of budget on this platform
  campaign_type: string; // e.g. "Advantage+ Shopping (CBO)"
  targeting: string; // 1-2 sentence targeting direction
  creatives: CreativeAngle[]; // Specific recommended creatives
}

